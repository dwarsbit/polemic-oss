/** The icons the panel draws; apps may pass their own nodes instead. */
export const ICON_NAMES = Object.keys(PATHS);

/** A 24px Lucide icon at `size`, in the text color. Unknown names draw nothing. */
export function Icon({
  name,
  size = 16,
  className,
}: {
  name: string;
  size?: number;
  className?: string;
}) {
  const paths = PATHS[name];
  if (!paths) return null;
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.75}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden
      className={className}
    >
      {paths}
    </svg>
  );
}

